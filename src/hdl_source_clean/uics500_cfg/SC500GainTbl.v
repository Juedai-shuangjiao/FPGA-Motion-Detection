`timescale 1ns / 1ps
//////////////////////////////////////////////////////////////////////////////////
// 模块：SC500GainTbl —— 增益值 → 模拟增益寄存器值
// 档位：1x(0x03) 2x(0x07) 4x(0x0F) 8x(0x1F) 12x(0x2F)
//////////////////////////////////////////////////////////////////////////////////
module SC500GainTbl(
        input            I_clk,
        input            I_rstn,
        input  [7:0]     I,          // 改成 8 位（原来 7 位不够装 12x 档）
        output reg [15:0] O
);
    always @(posedge I_clk) begin
        O <= 16'h0000;
        case (I[7:5])             // 高 3 位选档位
            3'd0 : O <= {8'h03, 8'h20 + I[4:0]};   // 1x 档
            3'd1 : O <= {8'h07, 8'h20 + I[4:0]};   // 2x 档
            3'd2 : O <= {8'h0F, 8'h20 + I[4:0]};   // 4x 档
            3'd3 : O <= {8'h1F, 8'h20 + I[4:0]};   // 8x 档
            3'd4 : O <= {8'h2F, 8'h20 + I[4:0]};   // 12x 档
            default : O <= 16'h0000;
        endcase
    end

endmodule