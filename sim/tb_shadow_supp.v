//========================================================
// tb：shadow_supp 阴影抑制仿真
// 场景：6 类像素各 1 项断言（数值与 Python 300 样本验证同源）
//========================================================
`timescale 1ns/1ps
module tb_shadow_supp;
    reg [7:0] br, bg, bb, cr, cg, cb;
    wire sh;
    integer fails = 0;

    shadow_supp u_dut (.I_bg_r(br), .I_bg_g(bg), .I_bg_b(bb),
                       .I_cur_r(cr), .I_cur_g(cg), .I_cur_b(cb), .O_shadow(sh));

    task check(input integer idx, input string name, input exp);
        begin
            #10;
            $display("%0d %s: shadow=%0b（期望 %0b）", idx, name, sh, exp);
            if(sh !== exp) begin $display("FAIL: %s", name); fails = fails + 1; end
            else $display("PASS: %s", name);
        end
    endtask

    initial begin
        // 1. 背景白墙噪声（200±8）：亮度差小 → 非阴影（前景判定交给阈值层）
        br=203; bg=208; bb=195; cr=205; cg=196; cb=202;
        check(1, "背景噪声", 1'b0);
        // 2. 手影子（色度不变、亮度降 30%）：(200,180,170)→(140,126,119)
        br=200; bg=180; bb=170; cr=140; cg=126; cb=119;
        check(2, "手阴影（亮度降30%）", 1'b1);
        // 3. 前景手肤色：(200,200,200) 背景 → (220,170,150)
        br=200; bg=200; bb=200; cr=220; cg=170; cb=150;
        check(3, "前景手（肤色）", 1'b0);
        // 4. 深灰实体：(200,200,200) → (90,90,90)（亮度砍半，兜底保留）
        br=200; bg=200; bb=200; cr=90; cg=90; cb=90;
        check(4, "深灰实体（亮度砍半）", 1'b0);
        // 5. 轻微亮度波动：(200,200,200) → (190,190,190)（dy=-40 未到 -48）
        br=200; bg=200; bb=200; cr=190; cg=190; cb=190;
        check(5, "轻微亮度波动", 1'b0);
        // 6. 彩色物体阴影边缘（亮度降 20% 色度略变）：(150,100,80)→(120,80,64)
        br=150; bg=100; bb=80; cr=120; cg=80; cb=64;
        check(6, "彩色表面阴影", 1'b1);

        // 7. 灰白墙前的手（2026-11-02 修复：背景色度 s_bg=0 <12 → 不判阴影，手保留涂白）
        br=200; bg=200; bb=200; cr=170; cg=160; cb=150;
        check(7, "白墙前的手(背景无色度)", 1'b0);
        // 8. 彩色墙前的手（s_bg 高但手色度差大 ds>25 → 不判阴影）
        br=180; bg=140; bb=100; cr=170; cg=160; cb=150;
        check(8, "彩色墙前的手(色度差大)", 1'b0);
        // 9. 白墙前的灰衣服（s_bg=0 → 不判阴影）
        br=200; bg=200; bb=200; cr=120; cg=120; cb=120;
        check(9, "白墙前的灰衣服", 1'b0);

        // 10. 水管挡光（金属灰变暗，色度不变 ds=0，但 s_bg=0<12）→ v2 不判阴影
        //    （v3 能滤它，但代价是误滤手内部暗区——2026-11-03 取舍：演示涂白完整性优先，
        //     灰墙阴影涂白无害、可接受）
        br=100; bg=100; bb=100; cr=70; cg=70; cb=70;
        check(10, "水管挡光(灰表面变暗,s_bg<12不滤)", 1'b0);
        // 11. 白墙前的深肤色手（色度升 ds>0 且 dy<-280 兜底）→ 不判阴影
        br=200; bg=200; bb=200; cr=150; cg=120; cb=100;
        check(11, "深肤色手(双重保护)", 1'b0);
        // 12. 鲜艳背景上的真影子（s_bg=80，ds=-24<-6）→ 判阴影
        br=180; bg=140; bb=100; cr=126; cg=98; cb=70;
        check(12, "鲜艳背景真影子(ds<-6)", 1'b1);
        // 13. 白墙前的手内部暗区（2026-11-03 回退核心场景：亮度降 dy≈-80、
        //     色度几乎不升 ds≈-2，白墙 s_bg=0）→ v2 不判阴影、涂白保留
        //     （v3 下 |ds|=2 ≤ 容忍 4 会误判阴影滤掉 → 涂白稀疏的根因）
        br=200; bg=200; bb=200; cr=170; cg=165; cb=162;
        check(13, "白墙前手内部暗区(回退核心场景)", 1'b0);

        $display("===== 结束：%0d 失败 =====", fails);
        $finish;
    end
endmodule
