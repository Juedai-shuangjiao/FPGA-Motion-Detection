//========================================================
// 模块：thr_adaptive —— 差分阈值亮度自适应查表
// 功能：根据全图平均亮度（ae_set 的 S_avg，8bit）输出阈值档位。
//       自然光噪声根因：亮度高 → 像素波动绝对值大 → 固定阈值误检。
//       查表策略（星点分割专利 CN104835177A 自适应阈值思想 + 实测增益分界）：
//         avg <  80（夜晚/暗室）→ 档 25（噪声小，低阈值保灵敏度）
//         avg 80~139（室内）    → 档 40（默认）
//         avg 140~199（亮环境） → 档 60
//         avg >= 200（强光）    → 档 80
//       输出 2bit 档位编码与 bg_read I_thr_sel 完全一致（00=25 01=40 10=60 11=80）。
// 资源：3 个 8bit 比较器 + 2bit mux ≈ 十几 LUT，零时序负担。
// 用法：I_avg 接 ae_set O_avg（或跨域打拍值），O_thr_sel 接 bg_read I_thr_sel 的
//       mux 分支（检测模式用本输出，其他用 SW1/SW2 手动档——顶层选择）。
//========================================================
module thr_adaptive (
    input  wire [7:0] I_avg,       //全图平均亮度（8bit，ae_set 输出，帧级更新）
    output wire [1:0] O_thr_sel    //阈值档位：00=25 01=40 10=60 11=80
);
    assign O_thr_sel = (I_avg >= 8'd200) ? 2'b11 :
                       (I_avg >= 8'd140) ? 2'b10 :
                       (I_avg >= 8'd80)  ? 2'b01 : 2'b00;
endmodule
